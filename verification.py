
from models import ResearchConstraints, ResearchPaper, ResearchResult
from validation import matches_constraints


def verify_result(result: ResearchResult, candidates: list[ResearchPaper], constraints: ResearchConstraints,) -> ResearchResult:
    """Verify the LLM's selection against retrieved OpenAlex data."""

    if not result.found or result.paper is None:
        return ResearchResult(
            found=False,
            paper=None,
            explanation=result.explanation,
        )

    selected = result.paper

    # Identify the selected paper by title and publication year.
    # Never trust the metadata copied into the LLM's output.
    for candidate in candidates:
        same_title = (" ".join(candidate.title.lower().split()) == " ".join(selected.title.lower().split()))
        same_year = candidate.year == selected.year

        if same_title and same_year:
            if not matches_constraints(candidate, constraints):
                break

            # Return the original OpenAlex metadata, not the
            # potentially modified metadata generated by the LLM.
            return ResearchResult(
                found=True,
                paper=candidate,
                explanation=result.explanation,
            )

    return ResearchResult(
        found=False,
        paper=None,
        explanation="The selected paper could not be verified against the retrieved OpenAlex results and constraints.",
    )
